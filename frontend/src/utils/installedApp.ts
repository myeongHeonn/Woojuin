/**
 * 설치된 앱(홈 화면에서 띄운 PWA)으로 실행 중인지 — 브라우저 탭이면 false.
 *
 * 실행 방식은 실행 중에 바뀌지 않으므로 모듈 로드 시 한 번만 판정한다.
 *
 * ── 어디에 쓰는가 ────────────────────────────────────────────────────────────
 * 주요 뷰 전환(하단 탭바·뷰바·워크스페이스 전환)을 `replace` 로 만들어 **히스토리를 쌓지
 * 않게** 하는 데 쓴다. 네이티브 앱에서 탭을 옮기는 것이 뒤로가기 스택을 만들지 않는 것과 같다.
 *
 * 그러면 뷰에 있을 때 히스토리 항목이 하나뿐이라
 *   - 안드로이드: 시스템 뒤로가기가 앱을 닫는다
 *   - iOS: 엣지 스와이프가 아무 일도 하지 않는다 (되돌아갈 뒤가 없다)
 * 가 된다. 둘 다 설치된 앱에서 기대되는 동작이다.
 *
 * ── 왜 브라우저 탭은 제외하는가 ──────────────────────────────────────────────
 * 웹에서는 뒤로가기가 정상으로 동작해야 한다. 실제로 앱 전체에 걸었을 때 뷰를 옮긴 뒤
 * 뒤로가기를 누르면 **탭에 사이트가 남지 않았다**(실측). 웹 사용자는 뒤로가기로 이전 화면에
 * 돌아가기를 기대한다.
 *
 * ── 왜 전역으로 pushState 를 갈아 끼우지 않는가 ──────────────────────────────
 * 그 방식도 시도했는데, 히스토리를 **한 항목으로 고정**해 버리므로 뷰 전환이 아닌 이동까지
 * 함께 죽는다. 예를 들어 가입 화면에서 개인정보처리방침을 열면 뒤로가기로 가입 화면에 돌아갈
 * 수 없게 된다. 쌓지 말아야 할 것은 "뷰 전환"이지 모든 이동이 아니다.
 */
export const IS_INSTALLED_APP =
  window.matchMedia('(display-mode: standalone)').matches ||
  // iOS 사파리는 display-mode 를 알려주지 않고 이 비표준 값을 쓴다
  (window.navigator as Navigator & { standalone?: boolean }).standalone === true;
