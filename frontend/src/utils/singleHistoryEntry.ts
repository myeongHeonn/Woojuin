/**
 * 히스토리 항목을 늘리지 않게 만든다 — 뒤로가기가 앱 안을 걷지 않고 곧바로 앱을 벗어난다.
 *
 * 설치된 앱에서 원하는 동작이 그것이기 때문이다. 안드로이드는 뒤로가기 한 번에 앱이 닫히고,
 * iOS 는 엣지 스와이프가 아무 일도 하지 않는다. 화면 사이 이동은 화면 안의 버튼으로만 한다.
 *
 * ── 왜 라우터 옵션이 아니라 pushState 를 바꾸는가 ─────────────────────────────
 * React Router v6 에는 "항상 replace" 스위치가 없다. 그래서 대안은 모든 `<Link>`·`<NavLink>`
 * 와 `navigate()` 호출에 replace 를 하나하나 붙이는 것뿐인데, 지금 세는 것만 서른 곳이 넘고
 * **새로 추가되는 화면이 빠뜨리면 조용히 어긋난다.** 원하는 성질이 "앱 전체에서 항상 하나"라
 * 전역 한 곳에서 보장하는 편이 맞다.
 *
 * 라우터는 내부적으로 push 를 `history.pushState` 로 낸다. 그것만 replaceState 로 돌리면
 * 라우터를 거치지 않는 이동까지 함께 덮인다.
 *
 * ── 딸려오는 결과 ────────────────────────────────────────────────────────────
 * `navigate(-1)` 은 히스토리에 뒤가 없으므로 앱을 벗어난다. 그래서 화면 안의 "뒤로" 버튼은
 * 히스토리를 쓰지 않고 갈 곳을 직접 지정한다(hooks/useGoBack 참고).
 *
 * 모달은 영향이 없다 — 라우트가 아니라 컴포넌트 state 로 열고 닫는다.
 *
 * StrictMode 가 이 파일을 두 번 실행할 일은 없다(모듈 최상단이 아니라 main 에서 한 번 부른다).
 * 다만 두 번 불려도 안전하다 — 이미 갈아둔 함수를 다시 갈아도 결과가 같다.
 */
export const keepSingleHistoryEntry = (): void => {
  // replaceState 를 미리 붙잡아 두지 않고 **부를 때마다 찾는다.** 이 페이지는 Clarity·GTM 을
  // 싣고, 그런 스크립트는 SPA 이동을 잡으려고 history API 를 감싼다 — 미리 잡아 두면 우리보다
  // 늦게 감싼 래퍼를 건너뛰게 된다.
  window.history.pushState = (data, unused, url) => {
    window.history.replaceState(data, unused, url);
  };
};
