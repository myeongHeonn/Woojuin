    CONSTRAINT fk_workspace_members_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
    CONSTRAINT ck_workspace_members_role CHECK (role IN ('OWNER', 'MEMBER'))
);

-- ===========================================================================
