-- V1: 초기 스키마 (Flyway 도입 기준선)
--
-- 이 파일은 2026-07-29 시점의 **운영/개발 DB 실제 스키마**를 그대로 옮긴 것이다.
-- 그때까지는 Hibernate `ddl-auto: update` 가 엔티티에서 스키마를 만들어 왔고,
-- 이 마이그레이션 이후로는 스키마 변경이 전부 이 디렉터리의 SQL 파일로만 이뤄진다.
--
-- 작성 근거: dev/prod 양쪽 `pg_dump --schema-only` 를 떠서 비교했다. 제약조건·타입에 의미 있는
-- 차이가 없었고 **컬럼 추가 순서만** 달랐다(`update` 가 두 환경에서 서로 다른 시점에 컬럼을
-- 붙인 흔적). dev 덤프(2026-07-30) 기준 + 이후 엔티티 변경(FCM 알림 2테이블, 탈퇴·튜토리얼
-- 컬럼 — 2026-07-31)을 반영했으며 컬럼 순서는
-- 엔티티 기준으로 정리했다. 순서는 어떤 동작에도 영향이 없다(JPA 는 컬럼을 이름으로 참조).
--
-- ⚠️ prod 는 이 시점에 `categories.description` 과 `item_embeddings` 가 **없다**(AI 기능이
--    main 에 아직 머지되지 않았다). 그 격차는 V3 가 멱등하게 메운다 — Flyway 는 Hibernate 보다
--    먼저 실행되므로 `ddl-auto: validate` 가 컬럼 누락으로 기동을 실패시키기 전에 채워진다.
--
-- ⚠️ 이미 테이블이 있는 DB(dev/prod/팀원 로컬)에는 `spring.flyway.baseline-on-migrate=true`
--    때문에 이 파일이 **적용되지 않는다** — "V1 은 이미 적용된 상태"로 간주하고 V2 부터 실행된다.
--    따라서 이 파일이 실제로 실행되는 건 **빈 DB** 뿐이다(신규 팀원, CI, 로컬 초기화).
--
-- 📌 제약조건 이름은 **읽을 수 있는 이름으로 새로 정했다**(`pk_users`, `uk_users_provider`, …).
--    기존 DB 에는 Hibernate 가 붙인 이름이 남아 있다 — PK/CHECK 는 규칙적이지만
--    (`users_pkey`, `items_type_check`) UNIQUE/FK 10 개는 테이블·컬럼명을 해시한
--    `ukcbysvpk95086ud4n4g6mkspai` 꼴이라 읽을 수 없다.
--
--    그대로 두면 **환경마다 제약조건 이름이 갈린다**(기존 DB = Hibernate 이름, 새 DB = 이 파일의
--    이름). 이름은 애플리케이션 코드가 참조하지 않지만 **마이그레이션이 참조한다** — 예를 들어
--    enum 에 값을 추가할 때 CHECK 를 지우고 다시 만들어야 하는데, 그 SQL 이 한쪽 환경에서
--    반드시 실패한다. 그래서 **V2 가 기존 DB 의 이름 23 개를 이 파일의 이름으로 개명**해
--    모든 환경을 수렴시킨다(V2 는 새 DB 에서는 아무 것도 하지 않는다).

-- ===========================================================================
-- pgvector 익스텐션 (의미 기반 검색 + 우주 뷰 3D 좌표)
-- ===========================================================================
-- `vector(1536)` 타입을 쓰려면 먼저 있어야 한다. compose 가 postgres 를
-- `pgvector/pgvector:pg16` 으로 고정하므로 익스텐션 파일은 이미지에 들어 있다
-- — 옛 `postgres:16-alpine` 컨테이너로 돌리면 여기서 마이그레이션이 실패한다(의도된 fail-fast:
--   조용히 임베딩만 꺼지는 것보다 원인을 즉시 드러내는 게 낫다).
CREATE EXTENSION IF NOT EXISTS vector;

-- ===========================================================================
-- users
-- ===========================================================================
CREATE TABLE users (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at            timestamp(6) with time zone NOT NULL,
    updated_at            timestamp(6) with time zone NOT NULL,
    avatar_color          character varying(20)  NOT NULL,
    -- 회원 탈퇴(soft delete). NULL = 활성 회원.
    deleted_at            timestamp(6) with time zone,
    email                 character varying(255) NOT NULL,
    email_verified        boolean                NOT NULL,
    nickname              character varying(50)  NOT NULL,
    password_hash         character varying(255),
    -- 최초 이용 안내(튜토리얼) 완료 여부 — 개인/공유 워크스페이스 독립 관리.
    -- DEFAULT 는 엔티티의 columnDefinition 과 일치시킨 것(기존 행을 false 로 안전하게 채움).
    personal_tutorial_completed          boolean NOT NULL DEFAULT false,
    shared_workspace_tutorial_completed  boolean NOT NULL DEFAULT false,
    -- 개인 워크스페이스 id. 연관 매핑이 아니라 생 id 로 들고 있어 FK 가 없다(아래 주석 참고).
    personal_workspace_id bigint,
    profile_image_url     text,
    provider              character varying(20)  NOT NULL,
    provider_id           character varying(100),

    CONSTRAINT pk_users PRIMARY KEY (id),

    -- 소셜 로그인 중복 가입 방지. LOCAL 가입은 provider_id 가 NULL 이라 이 제약이 걸리지 않는다
    -- (Postgres 는 NULL 을 서로 다른 값으로 취급).
    CONSTRAINT uk_users_provider UNIQUE (provider, provider_id),

    -- CHECK 제약은 Hibernate 가 @Enumerated(STRING) 에서 자동 생성한 것을 옮긴 것이다.
    -- ⚠️ enum 에 값을 추가하면 이 목록도 마이그레이션으로 같이 늘려야 한다.
    --    `ddl-auto: update` 는 기존 CHECK 를 갱신하지 않아, 새 값을 저장하는 순간
    --    제약조건 위반으로 실패한다(기동은 정상이라 배포 시점에는 안 드러난다).
    CONSTRAINT ck_users_avatar_color CHECK (avatar_color IN (
        'RED', 'ORANGE', 'YELLOW', 'GREEN', 'BLUE', 'NAVY',
        'PURPLE', 'PINK', 'CRIMSON', 'BLACK', 'WHITE')),
    CONSTRAINT ck_users_provider CHECK (provider IN ('LOCAL', 'KAKAO', 'GOOGLE'))
);

-- ⚠️ email 에 UNIQUE 가 없다 — 현재 스키마를 그대로 옮긴 결과다.
--    가입 시 중복 검사를 애플리케이션에서만 하고 있어, 동시 요청이 겹치면 같은 이메일의
--    LOCAL 계정이 둘 생길 수 있다. 추가는 기존 중복 데이터 확인이 필요해 V1 에서는 하지 않았다.
--    → 백로그: `CREATE UNIQUE INDEX ... ON users(email) WHERE provider = 'LOCAL'` 검토

