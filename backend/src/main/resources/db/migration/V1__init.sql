-- ===========================================================================
-- items
-- ===========================================================================
-- ⚠️ workspace_id / created_by 에 FK 가 없다 — 엔티티가 연관 매핑(@ManyToOne) 대신 생 id
--    (`Long workspaceId`)를 들고 있어서 Hibernate 가 FK 를 만들지 않았다. 현재 스키마를
--    그대로 옮긴 것이고, 추가하려면 기존 고아 행 확인이 필요하다 → 백로그.
CREATE TABLE items (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at            timestamp(6) with time zone NOT NULL,
    updated_at            timestamp(6) with time zone NOT NULL,
    address               character varying(300),
    content               text,
    created_by            bigint                NOT NULL,
    -- 소프트 삭제(휴지통). NULL = 활성. 아래 부분 인덱스들이 이 컬럼을 조건으로 쓴다.
    deleted_at            timestamp(6) with time zone,
    favorite              boolean               NOT NULL,
    lat                   double precision,
    lng                   double precision,
    preview_description   text,
    preview_thumbnail_url text,
    s3key                 character varying(500),
    status                character varying(15) NOT NULL,
    summary               text,
    thumbnails3key        character varying(500),
    title                 character varying(500),
    type                  character varying(10) NOT NULL,
    url                   text,
    workspace_id          bigint                NOT NULL,

    CONSTRAINT pk_items PRIMARY KEY (id),
    CONSTRAINT ck_items_status CHECK (status IN ('PROCESSING', 'DONE', 'PARTIAL', 'FAILED')),
    CONSTRAINT ck_items_type   CHECK (type   IN ('URL', 'IMAGE', 'MEMO'))
);

-- 활성 아이템 조회의 기본 인덱스. 목록(ORDER BY created_at DESC LIMIT n)과 검색이 함께 쓴다.
--
-- deleted_at 을 인덱스 "컬럼"이 아니라 WHERE 조건으로 뺀 게 핵심이다. 컬럼으로 넣으면
-- btree 가 정렬 순서를 보장하지 못해 플래너가 Bitmap 스캔 + Sort 로 떨어지고, LIMIT 28 인데도
-- 워크스페이스의 활성 아이템을 전부 읽는다. 부분 인덱스로 두면 정렬 컬럼이
-- (workspace_id, created_at) 만 남아 Index Scan 으로 앞 28건만 읽는다
-- — 20만 건/대상 1만 건 기준 6.4ms → 0.19ms.
--
-- 검색은 관련도로 정렬해 created_at 순서를 못 쓰지만, 대상을 해당 워크스페이스의 활성
-- 아이템으로 좁혀준다 — 검색이 텍스트 인덱스 없이 성립하는 건 전적으로 이 인덱스 덕분이다.
-- 휴지통 조회(deleted_at IS NOT NULL)는 이 인덱스를 쓰지 못한다(저트래픽이라 감수).
CREATE INDEX idx_items_ws_active ON items (workspace_id, created_at DESC)
    WHERE deleted_at IS NULL;

-- 지도 조회(GET /items/geo, FR-032) 전용. 좌표가 있는 아이템은 워크스페이스 전체의 소수라
-- (링크·메모 대부분은 위치가 없다) 조건을 인덱스 WHERE 로 밀어넣으면 인덱스가 아주 작아진다.
-- 좌표를 별도 테이블로 분리하지 않고 items 컬럼으로 둘 수 있는 근거가 이 인덱스다.
-- 정렬 컬럼을 두지 않은 건 지도 조회에 ORDER BY 도 페이지네이션도 없기 때문(응답이 좌표 배열).
CREATE INDEX idx_items_ws_geo ON items (workspace_id)
    WHERE lat IS NOT NULL AND lng IS NOT NULL AND deleted_at IS NULL;

-- 📌 위 두 인덱스는 Flyway 도입 전까지 `ItemIndexInitializer`(ApplicationReadyEvent 에서
--    CREATE INDEX IF NOT EXISTS 실행)가 만들고 있었다. 부분 인덱스는 JPA 애노테이션으로
--    표현할 수 없어 애플리케이션 코드가 DDL 을 대신 실행한 것이다. 이제 스키마의 소유권이
--    이 파일로 넘어왔으니 그 클래스는 제거 대상이다(성능 근거는 위 주석으로 옮겨 왔다).
--    ⚠️ 그 클래스의 경고는 여기서도 유효하다: **items 에 GENERATED 컬럼을 추가하면 안 된다.**
--       `ddl-auto` 가 남아 있는 환경에서 content 의 타입 변경 ALTER 가 거부돼 기동이 실패한다.

