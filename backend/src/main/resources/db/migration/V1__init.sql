-- ===========================================================================
-- notification_tokens (FCM 기기 토큰 — User:Token = 1:N)
-- ===========================================================================
CREATE TABLE notification_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint                 NOT NULL,
    -- 토큰은 기기/브라우저 설치 단위로 유일 — 같은 토큰 재등록 시 소유자만 갱신된다(reassignTo)
