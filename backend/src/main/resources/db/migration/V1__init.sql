    CONSTRAINT fk_workspaces_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_workspaces_type CHECK (type IN ('PERSONAL', 'TEAM'))
);

-- ===========================================================================
