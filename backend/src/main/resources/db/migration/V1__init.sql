-- ===========================================================================
-- notifications (인앱 알림함 — 아이템 처리 완료 시 생성)
-- ===========================================================================
-- ⚠️ user_id/item_id 에 FK 없음 — 엔티티가 생 id 를 쓰는 기존 패턴(items 등)과 동일. → 백로그
CREATE TABLE notifications (
