-- ===========================================================================
-- item_embeddings (의미 기반 검색 + 우주 뷰 3D 좌표)
-- ===========================================================================
-- JPA 엔티티가 **아니다** — `vector(1536)` 을 `ddl-auto` 아래 두면 Hibernate 가 매 기동마다
-- 타입 재검사 경로에 들어가고(items 의 GENERATED 컬럼 함정과 같은 계열), 접근 패턴이 전부
-- 단건 upsert / 워크스페이스 벌크 조회라 JPA 의 이점도 없다. 유사도 검색도 pgvector 연산자
-- (`<=>`)를 쓰는 네이티브 SQL 이다. 상세 근거는 ItemEmbeddingSchemaInitializer javadoc.
--
-- 📌 그 클래스가 기동 시 이 DDL 을 직접 실행하고 있었다(Flyway 가 없어서). 이제 소유권이
--    이 파일로 넘어왔으니 **제거 대상**이다 — 남겨 둬도 전부 IF NOT EXISTS 라 no-op 이지만,
--    남겨 두면 새 환경에서 Postgres 기본 제약조건 이름(`item_embeddings_pkey`)을 다시 만들어
--    이름 규칙이 또 갈린다. 제거는 백엔드 담당 판단이라 이 마이그레이션에 포함하지 않았다.
CREATE TABLE item_embeddings (
    -- item_id 가 PK — 아이템당 임베딩 하나. 영구 삭제 시 함께 지워지도록 FK CASCADE.
    -- (휴지통 soft delete 는 행을 남기고, 조회 쪽에서 items.deleted_at 으로 거른다)
    item_id         bigint NOT NULL,
    -- workspace_id 를 중복 보관하는 건 재계산·좌표 조회가 워크스페이스 단위 벌크라
    -- 매번 items 를 조인해 거를 필요를 줄이기 위해서다.
    workspace_id    bigint NOT NULL,
    embedding       vector(1536) NOT NULL,
    embedding_model character varying(100),
    input_hash      character varying(100),
    -- x/y/z 가 nullable 인 건 "임베딩은 저장됐지만 아직 좌표 재계산 전"인 순간이 있어서다.
    x               double precision,
    y               double precision,
    z               double precision,
    updated_at      timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT pk_item_embeddings PRIMARY KEY (item_id),
    CONSTRAINT fk_item_embeddings_item FOREIGN KEY (item_id) REFERENCES items (id) ON DELETE CASCADE
);

CREATE INDEX idx_item_embeddings_ws ON item_embeddings (workspace_id);
